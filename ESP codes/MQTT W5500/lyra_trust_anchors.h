// BearSSL trust anchor for lyra-app.co.in, used by SSLClient to validate the
// TLS certificate over the Ethernet path (see makeEthernetHTTPRequest()).
//
// This is ISRG Root X2 -- the root of the chain that signs lyra-app.co.in's
// live certificate as of 2026-09-23 (leaf -> Let's Encrypt "YE2" intermediate
// -> ISRG Root X2). Pinning to the ROOT rather than the leaf/intermediate is
// deliberate: leaf certs rotate every ~90 days and intermediates can also
// change, but ISRG Root X2 is valid until 2040 -- SSLClient validates the
// chain the server presents against this pinned root, so routine cert
// renewals on the server side don't require reflashing every machine.
//
// Extracted directly from https://letsencrypt.org/certs/isrg-root-x2.pem via
// openssl (subject DN DER bytes + EC public key point), matching the format
// SSLClient's own pycert_bearssl tool produces -- see
// https://github.com/OPEnSLab-OSU/SSLClient/blob/master/TrustAnchors.md if
// this ever needs regenerating (e.g. if lyra-app.co.in's CA changes).
//
// Regenerate if: TLS handshakes start failing fleet-wide after a server-side
// cert/CA change, or you point this firmware at a different domain.

